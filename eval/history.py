"""Experiment history: every evaluation run is appended to eval/history.jsonl (committed), so the score of every
model / grammar / policy version stays traceable — a minimal MLflow without a server.

    python -m eval.ab ... --log "note"          # eval/ab.py appends one record per run
    python -m eval.history                      # table of all runs (stdout)
    python -m eval.history --md docs/EXPERIMENTS.md

A record: when, git commit (+ dirty flag), sha256 prefix of every artifact (model, policy, calibrator, gazetteer),
the note, and the jury score per gold set and mode (+ all-4-per-record and ms/record).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HISTORY = ROOT / "eval" / "history.jsonl"
ARTIFACTS = ["model.onnx", "model_meta.json", "arbiter_policy.json", "calibrator.json", "gazetteer.sqlite"]


def _git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, timeout=10).stdout.strip()
    except Exception:  # noqa: BLE001 — history must never break an evaluation
        return ""


def _sha(path: Path) -> str | None:
    if not path.exists():
        return None
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:12]


def fingerprint(artifacts_dir: Path | None = None) -> dict:
    import os
    art = Path(artifacts_dir or os.environ.get("JANA_ARTIFACTS_DIR", ROOT / "api" / "artifacts"))
    return {"commit": _git("rev-parse", "--short", "HEAD"), "dirty": bool(_git("status", "--porcelain", "--", "api", "training", "eval")),
            "branch": _git("rev-parse", "--abbrev-ref", "HEAD"), "artifacts": {a: _sha(art / a) for a in ARTIFACTS}}


def append(report: dict, note: str = "", kind: str = "ab", path: Path = HISTORY) -> dict:
    """report: {gold_set: {mode: score dict from eval.metric.score (+ ms_per_record)}}."""
    rec = {"time": time.strftime("%Y-%m-%d %H:%M"), "kind": kind, "note": note, **fingerprint(), "results": {}}
    for gold, modes in report.items():
        for mode, r in modes.items():
            if isinstance(r, dict) and "score_pct" in r:
                rec["results"].setdefault(gold, {})[mode] = {
                    "score": r["score_pct"], "all4": round(100 * r["address_all4_per_record"], 2),
                    "n": r["n"], "ms": r.get("ms_per_record")}
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    return rec


def load(path: Path = HISTORY) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def table(records: list[dict], mode: str = "hybrid") -> str:
    sets = []
    for r in records:
        for g in r["results"]:
            if g not in sets:
                sets.append(g)
    head = "| when | commit | model | note | " + " | ".join(sets) + " |"
    sep = "|---|---|---|---|" + "---|" * len(sets)
    rows = [head, sep]
    for r in records:
        cells = []
        for g in sets:
            m = r["results"].get(g, {})
            v = m.get(mode) or m.get("rules")
            cells.append("" if v is None else f"{v['score']:.2f}" + ("" if mode in m else " ʳ"))
        model = (r.get("artifacts") or {}).get("model.onnx") or "—"
        rows.append(f"| {r['time']} | {r.get('commit', '')}{'*' if r.get('dirty') else ''} | {model[:7]} | {r.get('note', '')} | "
                    + " | ".join(cells) + " |")
    return "\n".join(rows)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mode", default="hybrid", choices=["hybrid", "model", "rules"])
    ap.add_argument("--md", help="write a markdown page (e.g. docs/EXPERIMENTS.md)")
    a = ap.parse_args(argv)
    recs = load()
    t = table(recs, a.mode)
    print(t)
    if a.md:
        Path(a.md).write_text(
            "# Experiment history\n\nGenerated by `python -m eval.history --md docs/EXPERIMENTS.md` from `eval/history.jsonl`; "
            "every `make ab` run appends one record (git commit, artifact hashes, scores). Jury-metric score, "
            f"mode **{a.mode}** (ʳ = rules only, no model in that run; `*` = uncommitted changes at run time). "
            "`test_handmade` is the held-out set.\n\n" + t + "\n", encoding="utf-8")
        print(f"→ {a.md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
